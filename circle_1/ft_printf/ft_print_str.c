#include "ft_printf.h"

void	ft_print_str(char *s, int *count)
{
	if (!s)
	{
		write(1, "(null)", 6);
		(*count) += 6;
		return ;
	}
	while (*s)
	{
		write(1, s, 1);
		s++;
		(*count)++;
	}
}
