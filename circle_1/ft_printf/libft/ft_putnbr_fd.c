#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	char	temp;
	long	num;

	num = (long)n;
	if (num < 0)
	{
		ft_putchar_fd('-', fd);
		num = -num;
	}
	if (num >= 10)
		ft_putnbr_fd(num / 10, fd);
	temp = (num % 10) + '0';
	ft_putchar_fd(temp, fd);
}
